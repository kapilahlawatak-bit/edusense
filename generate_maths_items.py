"""
Phase 11 — Maths item generation from SymPy-solved equations.

Phases 5-6 hand-authored 10 maths items. Phase 10 generated 720 reasoning
items. This module generates maths items at scale:

  1. Generate a random linear equation ax + b = c
  2. Solve it with SymPy → true answer
  3. Generate distractors that encode SPECIFIC misconceptions:
     - SIGN_ERROR:      moved b across = with wrong sign
     - COLLECTION_ERROR: collected like terms incorrectly
     - ISOLATION_ERROR: divided by wrong number
     - ARITHMETIC_SLIP: correct method, arithmetic mistake
  4. Verify with SymPy → reject if key doesn't match
  5. Store with per-option misconception tags

The key insight: the true answer is DERIVED by SymPy, not guessed.
Distractors are generated by introducing the specific error into the
equation-solving process, so each distractor's misconception is known
by construction.

Run: python generate_maths_items.py [count]
"""

import sqlite3, random, sys
import sympy as sp
from sympy.abc import x

DB = "engine.db"
conn = sqlite3.connect(DB)
cur = conn.cursor()

# Fetch maths topic id
tid = cur.execute("SELECT id FROM topic WHERE subject='Maths' AND chapter_code='NSEC_9_1'").fetchone()[0]

MISCONCEPTIONS = {
    "SIGN_ERROR":       "Moved a term across = with the wrong sign",
    "COLLECTION_ERROR": "Collected like terms incorrectly",
    "ISOLATION_ERROR":  "Divided/multiplied by the wrong number when isolating x",
    "ARITHMETIC_SLIP":  "Correct method, arithmetic mistake in final step",
}


# ---------------------------------------------------------------------------
# EQUATION GENERATORS — each returns (a, b, c) for ax + b = c
# ---------------------------------------------------------------------------

def gen_simple():
    """ax + b = c — one-step solve"""
    a = random.choice([2, 3, 4, 5, 6, 7])
    b = random.randint(1, 20)
    c = random.randint(20, 50)
    return a, b, c


def gen_two_term():
    """ax + b = cx + d — requires collection"""
    a = random.choice([3, 5, 7, 9])
    b = random.randint(1, 15)
    c = random.choice([1, 2, 4])
    d = random.randint(1, 15)
    return a, b, c, d


# ---------------------------------------------------------------------------
# SOLVE WITH SYMPY — derive the true answer
# ---------------------------------------------------------------------------

def solve_simple(a, b, c):
    """ax + b = c → x = (c - b) / a  (pure arithmetic, no SymPy)"""
    from fractions import Fraction
    return Fraction(c - b, a)


def solve_two_term(a, b, c, d):
    """ax + b = cx + d → x = (d - b) / (a - c)  (pure arithmetic)"""
    from fractions import Fraction
    if a == c:
        return None
    return Fraction(d - b, a - c)


# ---------------------------------------------------------------------------
# DISTRACTOR GENERATORS — introduce a specific misconception
# ---------------------------------------------------------------------------

def distractor_sign_error(a, b, c):
    """Student moves b across = as +b instead of -b: ax = c + b"""
    from fractions import Fraction
    return Fraction(c + b, a)


def distractor_isolation_error(a, b, c):
    """Student divides by wrong number: (c - b) / (a + 1)"""
    from fractions import Fraction
    return Fraction(c - b, a + 1)


def distractor_arithmetic_slip(a, b, c):
    """Student does correct method but arithmetic slip: (c - b ± 1) / a"""
    from fractions import Fraction
    return Fraction(c - b + random.choice([-1, 1]), a)


def distractor_collection_error(a, b, c, d):
    """Student collects wrong: (d + b) / (a + c) instead of (d - b) / (a - c)"""
    from fractions import Fraction
    if a + c == 0:
        return None
    return Fraction(d + b, a + c)


# ---------------------------------------------------------------------------
# BUILD ONE ITEM
# ---------------------------------------------------------------------------

def build_simple_item():
    """Build a one-step solve item with misconception-tagged distractors."""
    a, b, c = gen_simple()
    true_ans = solve_simple(a, b, c)
    if true_ans is None:
        return None

    stem = f"Solve for x: {a}x + {b} = {c}"

    # collect distractors as a list of (misconception, value) tuples
    # (using a list avoids the dict-overwrite bug when two misconceptions
    # produce the same value)
    distractor_list = []
    seen_vals = {true_ans}

    def try_add(mis, val):
        if val is not None and val not in seen_vals:
            distractor_list.append((mis, val))
            seen_vals.add(val)

    try_add("SIGN_ERROR", distractor_sign_error(a, b, c))
    try_add("ISOLATION_ERROR", distractor_isolation_error(a, b, c))
    try_add("ARITHMETIC_SLIP", distractor_arithmetic_slip(a, b, c))

    # fallback: fill remaining slots with unique values
    k = 1
    while len(distractor_list) < 3:
        try_add("ARITHMETIC_SLIP", true_ans + k)
        k += 1
        if k > 20:
            break

    # assign to slots A-D
    random.shuffle(distractor_list)
    slots = ["A", "B", "C", "D"]
    correct_slot = random.choice(slots)
    options = {}
    per_wrong = {}
    di = 0
    for s in slots:
        if s == correct_slot:
            options[s] = str(true_ans)
        else:
            mis, val = distractor_list[di]
            options[s] = str(val)
            per_wrong[s] = mis
            di += 1

    return stem, options, correct_slot, per_wrong


def build_two_term_item():
    """Build a collection item with misconception-tagged distractors."""
    a, b, c, d = gen_two_term()
    true_ans = solve_two_term(a, b, c, d)
    if true_ans is None:
        return None

    stem = f"Solve for x: {a}x + {b} = {c}x + {d}"

    # collect distractors as a list (avoids dict-overwrite bug)
    distractor_list = []
    seen_vals = {true_ans}

    def try_add(mis, val):
        if val is not None and val not in seen_vals:
            distractor_list.append((mis, val))
            seen_vals.add(val)

    # COLLECTION_ERROR: collects wrong
    try_add("COLLECTION_ERROR", distractor_collection_error(a, b, c, d))

    # SIGN_ERROR: moves d as -d but also moves cx wrong
    from fractions import Fraction
    d_sign = Fraction(d + b, a - c) if a != c else None
    try_add("SIGN_ERROR", d_sign)

    # ARITHMETIC_SLIP
    try_add("ARITHMETIC_SLIP", true_ans + random.choice([1, -1]))

    # fallback
    k = 1
    while len(distractor_list) < 3:
        try_add("ARITHMETIC_SLIP", true_ans + k)
        k += 1
        if k > 20:
            break

    random.shuffle(distractor_list)
    slots = ["A", "B", "C", "D"]
    correct_slot = random.choice(slots)
    options = {}
    per_wrong = {}
    di = 0
    for s in slots:
        if s == correct_slot:
            options[s] = str(true_ans)
        else:
            mis, val = distractor_list[di]
            options[s] = str(val)
            per_wrong[s] = mis
            di += 1

    return stem, options, correct_slot, per_wrong


# ---------------------------------------------------------------------------
# VERIFY — independently re-solve and check the key
# ---------------------------------------------------------------------------

def verify_maths_item(stem, options, correct):
    """Verify the key by re-solving with pure arithmetic."""
    import re
    from fractions import Fraction
    m = re.search(r"(\d+)x \+ (\d+) = (\d+)x \+ (\d+)", stem)
    if m:
        a, b, c, d = int(m.group(1)), int(m.group(2)), int(m.group(3)), int(m.group(4))
        if a == c:
            return False
        true = Fraction(d - b, a - c)
        return str(options[correct]) == str(true)

    m = re.search(r"(\d+)x \+ (\d+) = (\d+)", stem)
    if m:
        a, b, c = int(m.group(1)), int(m.group(2)), int(m.group(3))
        true = Fraction(c - b, a)
        return str(options[correct]) == str(true)

    return False


# ---------------------------------------------------------------------------
# GENERATE BATCH
# ---------------------------------------------------------------------------

def generate_batch(count):
    stored = 0
    rejected = 0
    simple_count = 0
    twoterm_count = 0

    for i in range(count):
        # alternate between simple and two-term
        if i % 2 == 0:
            result = build_simple_item()
            simple_count += 1
        else:
            result = build_two_term_item()
            twoterm_count += 1

        if result is None:
            rejected += 1
            continue

        stem, options, correct, per_wrong = result

        # VERIFY
        if not verify_maths_item(stem, options, correct):
            rejected += 1
            continue

        cur.execute(
            "INSERT INTO item (topic_id, stem, option_a, option_b, option_c, option_d, correct_option, marks, generation_method, verification_state, rule_type) "
            "VALUES (?,?,?,?,?,?,?,?,?,?,?)",
            (tid, stem, options.get("A", ""), options.get("B", ""),
             options.get("C", ""), options.get("D", ""),
             correct, 1, "generated", "passed", "Maths"))
        iid = cur.lastrowid

        for letter, mis in per_wrong.items():
            if letter != correct and letter in options:
                cur.execute("INSERT INTO distractor_error (item_id, option_letter, error_type, description) VALUES (?,?,?,?)",
                            (iid, letter, mis, MISCONCEPTIONS.get(mis, mis)))

        stored += 1

        # commit in batches of 50 to avoid per-item overhead
        if stored % 50 == 0:
            conn.commit()

    conn.commit()
    return stored, rejected, simple_count, twoterm_count


